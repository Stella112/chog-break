// §E step 4: docs/TRAIT_REPORT.md from the generated manifest.
// Phase 1 extends this with gene mapping per value and recipe pair counts.
import { readFileSync, writeFileSync } from 'node:fs';
import { NONE, TRAIT_CATEGORIES, type ChogRecord } from '../src/core/types';
import { validateManifest } from './lib/validate';

const records = JSON.parse(readFileSync('public/data/chogs.json', 'utf8')) as ChogRecord[];
const validIds = JSON.parse(readFileSync('public/data/valid-token-ids.json', 'utf8')) as number[];
const problems = validateManifest(records);
const malformed = records.filter((r) => !r.image || !r.displayName || r.displayNumber === null);

const lines: string[] = [
  '# TRAIT_REPORT',
  '',
  `Generated by \`npm run data:report\` from \`public/data/chogs.json\` on ${new Date().toISOString()}.`,
  '',
  '## Totals',
  '',
  `- Records: **${records.length}**`,
  `- Minted token IDs (ownerOf scan): **${validIds.length}**, range ${validIds[0]}..${validIds.at(-1)}`,
  `- Malformed records (missing image/name/number): ${malformed.length ? malformed.map((r) => r.tokenId).join(', ') : 'none'}`,
  `- Validation vs §C3: ${problems.length ? problems.map((p) => `\n  - FAIL ${p}`).join('') : 'all checks pass'}`,
  '',
  '## Categories',
  '',
];
for (const cat of TRAIT_CATEGORIES) {
  const counts = new Map<string, number>();
  const rawForms = new Map<string, Set<string>>();
  for (const r of records) {
    const v = r.traits[cat];
    counts.set(v, (counts.get(v) ?? 0) + 1);
    const raw = r.attributes.find((a) => a.trait_type === cat);
    if (raw) {
      if (!rawForms.has(v)) rawForms.set(v, new Set());
      rawForms.get(v)!.add(String(raw.value));
    }
  }
  const absent = counts.get(NONE) ?? 0;
  const values = [...counts.entries()].filter(([v]) => v !== NONE).sort((a, b) => b[1] - a[1]);
  lines.push(`### ${cat} — ${values.length} normalized values · on ${records.length - absent} · absent on ${absent}`, '');
  lines.push('| Normalized value | Count | Raw spellings |', '|---|---|---|');
  for (const [v, n] of values) lines.push(`| ${v} | ${n} | ${[...(rawForms.get(v) ?? [])].join(' / ')} |`);
  lines.push('');
}
writeFileSync('docs/TRAIT_REPORT.md', lines.join('\n'));
console.log(`wrote docs/TRAIT_REPORT.md (${problems.length} validation problems)`);
