// §D5/§F Phase 1: re-count recipes against the real manifest, write docs/RECIPE_EXAMPLES.md
// and src/config/secretPairs.json (one pair per recipe whose mutant actually resolves to that recipe).
import { readFileSync, writeFileSync } from 'node:fs';
import { RECIPES } from '../src/core/recipes';
import { createMutant } from '../src/core/splice';
import type { ChogRecord } from '../src/core/types';
import { countRecipePairs } from './lib/recipeCounts';

const records = JSON.parse(readFileSync('public/data/chogs.json', 'utf8')) as ChogRecord[];
const byId = new Map(records.map((r) => [r.tokenId, r]));
const counts = countRecipePairs(records);

// Example pairs must produce that recipe after precedence; search for one if the first match is shadowed.
function exampleFor(id: string): [number, number] | undefined {
  const r = RECIPES.find((x) => x.id === id)!;
  const tiers = ['P0', 'P1'] as const;
  const xs = records.filter((c) => r.x(c.traits));
  const ys = records.filter((c) => r.y(c.traits));
  for (const a of xs)
    for (const b of ys) {
      if (a.tokenId === b.tokenId) continue;
      if (createMutant({ parentA: a, parentB: b, recipeTiers: tiers }).recipe?.id === id) return [a.tokenId, b.tokenId];
    }
  return undefined;
}

const lines = [
  '# RECIPE_EXAMPLES',
  '',
  'Generated by `npx tsx scripts/recipe-examples.ts` from the real manifest. Pair counts are unordered real pairs',
  'satisfying the condition (before precedence). Example pairs are token IDs that resolve to that recipe.',
  '',
  '| Recipe | Tier | Real pairs (spec) | Real pairs (manifest) | Example (token IDs) | Deep link |',
  '|---|---|---|---|---|---|',
];
const SPEC: Record<string, number> = {
  KING_BEAM: 14930, NUCLEAR_UNDEAD: 1800, THE_NAKED_KING: 2916, ARCHMAGE: 2232, VOLATILITY: 414, FWOG_LORD: 809,
  ESCAPE_VELOCITY: 720, WILDFIRE: 19099, LASER_SHOW: 26770, GOLDEN_BULL: 390, BEAR_MARKET: 3311, SKULL_AND_BONES: 1080,
  SHARK_WEEK: 4585, HONK_LORD: 1767, DOUBLE_RAINBOW: 2604, BTC_MAXI: 1157,
};
const secret: { recipe: string; a: number; b: number }[] = [];
const missing: string[] = [];
for (const r of RECIPES) {
  const ex = exampleFor(r.id);
  const n = counts.get(r.id)!.count;
  if (!ex) missing.push(r.id);
  if (ex) secret.push({ recipe: r.id, a: ex[0], b: ex[1] });
  const names = ex ? `${ex[0]} (${byId.get(ex[0])!.displayName}) × ${ex[1]} (${byId.get(ex[1])!.displayName})` : 'NONE';
  lines.push(`| ${r.name} | ${r.tier} | ${SPEC[r.id]} | ${n} | ${names} | ${ex ? `/?a=${ex[0]}&b=${ex[1]}` : '—'} |`);
}
writeFileSync('docs/RECIPE_EXAMPLES.md', lines.join('\n') + '\n');
writeFileSync('src/config/secretPairs.json', JSON.stringify(secret, null, 2) + '\n');
console.log(lines.slice(5).join('\n'));
if (missing.length) {
  console.error('Recipes without a real resolving pair:', missing.join(', '));
  process.exitCode = 1;
}
